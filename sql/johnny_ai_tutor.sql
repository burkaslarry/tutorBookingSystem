-- Tutor booking tables on the shared Render Postgres database (eventxp).
-- Names follow the storyseed_* prefix pattern: johnny_ai_tutor_*.

CREATE TABLE IF NOT EXISTS johnny_ai_tutor_bookings (
  id varchar(80) PRIMARY KEY,
  student varchar(60) NOT NULL,
  phone varchar(30) NOT NULL,
  course varchar(100) NOT NULL,
  date varchar(10) NOT NULL,
  time varchar(5) NOT NULL,
  status varchar(20) NOT NULL CHECK (status IN ('pending', 'checked-in', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS johnny_ai_tutor_bookings_date_time_idx
  ON johnny_ai_tutor_bookings (date, time);

CREATE TABLE IF NOT EXISTS johnny_ai_tutor_admins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(120) NOT NULL UNIQUE,
  password_salt varchar(128) NOT NULL,
  password_hash varchar(256) NOT NULL,
  role varchar(20) NOT NULL DEFAULT 'ADMIN',
  is_active integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS johnny_ai_tutor_auth_sessions (
  token varchar(128) PRIMARY KEY,
  admin_id integer NOT NULL REFERENCES johnny_ai_tutor_admins (id),
  expires_at varchar(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS johnny_ai_tutor_courses (
  id varchar(80) PRIMARY KEY,
  name varchar(100) NOT NULL,
  description text NOT NULL,
  price_cents integer NOT NULL,
  active integer NOT NULL DEFAULT 1,
  created_at varchar(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS johnny_ai_tutor_slots (
  id varchar(80) PRIMARY KEY,
  course_id varchar(80) NOT NULL REFERENCES johnny_ai_tutor_courses (id),
  date varchar(10) NOT NULL,
  start_time varchar(5) NOT NULL,
  end_time varchar(5) NOT NULL,
  capacity integer NOT NULL,
  created_at varchar(30) NOT NULL
);

CREATE INDEX IF NOT EXISTS johnny_ai_tutor_slots_date_idx
  ON johnny_ai_tutor_slots (date);

CREATE TABLE IF NOT EXISTS johnny_ai_tutor_registrations (
  id varchar(80) PRIMARY KEY,
  slot_id varchar(80) NOT NULL REFERENCES johnny_ai_tutor_slots (id),
  student_name varchar(60) NOT NULL,
  company_name varchar(120) NOT NULL DEFAULT '',
  phone varchar(30) NOT NULL,
  email varchar(120) NOT NULL,
  status varchar(20) NOT NULL,
  payment_method varchar(20) NOT NULL,
  payment_status varchar(20) NOT NULL,
  amount_cents integer NOT NULL,
  receipt_path varchar(255),
  receipt_mime varchar(80),
  receipt_data bytea,
  kpay_intent_id varchar(120),
  kpay_checkout_url text,
  confirmation_email_status varchar(30),
  confirmation_email_id varchar(120),
  reminder_email_status varchar(30),
  reminder_email_id varchar(120),
  reminder_sent_at varchar(30),
  created_at varchar(30) NOT NULL
);

CREATE INDEX IF NOT EXISTS johnny_ai_tutor_registrations_slot_idx
  ON johnny_ai_tutor_registrations (slot_id);
